use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use clap::Subcommand;

use crate::config::Config;

const SERVICE_NAME: &str = "rc003-omarchy.service";
const SERVICE_MARKER: &str = "# Generated by rc003-omarchy";

#[derive(Debug, Clone, Subcommand)]
pub enum ServiceCommand {
    /// Preview the generated user unit.
    Show,
    /// Show active/enabled state.
    Status,
    /// Install and optionally start the user service.
    Install {
        #[arg(long)]
        apply: bool,
        #[arg(long)]
        no_start: bool,
        #[arg(long)]
        force: bool,
    },
    /// Stop, disable, and remove the generated user service.
    Uninstall {
        #[arg(long)]
        apply: bool,
    },
}

pub fn run(command: ServiceCommand) -> Result<()> {
    match command {
        ServiceCommand::Show => show(),
        ServiceCommand::Status => status(),
        ServiceCommand::Install {
            apply,
            no_start,
            force,
        } => install(apply, no_start, force),
        ServiceCommand::Uninstall { apply } => uninstall(apply),
    }
}

fn unit_path() -> PathBuf {
    Config::default_path()
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join("systemd/user")
        .join(SERVICE_NAME)
}

fn quote(value: &Path) -> String {
    format!(
        "\"{}\"",
        value
            .display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('\'', "'\\''")
            .replace('"', "\\\"")
            .replace('$', "$$")
            .replace('`', "\\`")
            .replace('%', "%%")
    )
}

fn unit_text(executable: &Path, config: &Path) -> Result<String> {
    validate_safe_path(executable)?;
    validate_safe_path(config)?;
    Ok(format!(
        "{SERVICE_MARKER}\n[Unit]\nDescription=RC003 microphone and input bridge\nAfter=graphical-session.target pipewire.service\nPartOf=graphical-session.target\n\n[Service]\nType=simple\nExecStart=/usr/bin/newgrp input -c '{} run --config {}'\nRestart=on-failure\nRestartSec=2\nTimeoutStopSec=15\nKillMode=control-group\nUMask=0077\n\n[Install]\nWantedBy=graphical-session.target\n",
        quote(executable),
        quote(config),
    ))
}

fn validate_safe_path(path: &Path) -> Result<()> {
    let text = path.display().to_string();
    if text.is_empty()
        || !text
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '/' | '-'))
    {
        anyhow::bail!(
            "unsafe path {text:?}; only ASCII letters, digits, '.', '_', '/', and '-' are allowed"
        );
    }
    Ok(())
}

fn executable_path() -> PathBuf {
    if let Some(path) = std::env::var_os("XDG_BIN_HOME") {
        return PathBuf::from(path).join("rc003-omarchy");
    }
    PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".local/bin/rc003-omarchy")
}

fn generated_unit() -> Result<String> {
    unit_text(&executable_path(), &Config::default_path())
}

fn install_executable() -> Result<()> {
    let source = std::env::current_exe()?;
    let destination = executable_path();
    let parent = destination
        .parent()
        .context("executable path has no parent")?;
    std::fs::create_dir_all(parent)?;
    let temporary = destination.with_extension("tmp");
    std::fs::copy(&source, &temporary)?;
    std::fs::rename(&temporary, &destination)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&destination, std::fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

fn show() -> Result<()> {
    println!("{}\n\n{}", unit_path().display(), generated_unit()?);
    Ok(())
}

fn status() -> Result<()> {
    for property in ["is-active", "is-enabled"] {
        let output = std::process::Command::new("systemctl")
            .args(["--user", property, SERVICE_NAME])
            .output()
            .with_context(|| format!("systemctl --user {property}"))?;
        println!(
            "{}: {}",
            property.trim_start_matches("is-"),
            String::from_utf8_lossy(&output.stdout).trim()
        );
    }
    println!("unit: {}", unit_path().display());
    Ok(())
}

fn install(apply: bool, no_start: bool, force: bool) -> Result<()> {
    let path = unit_path();
    let unit = generated_unit()?;
    if !apply {
        println!("Would install {}:\n\n{}", path.display(), unit);
        return Ok(());
    }
    if path.exists() && !force {
        anyhow::bail!(
            "{} already exists; use --force to replace it",
            path.display()
        );
    }
    install_executable()?;
    let parent = path.parent().context("service path has no parent")?;
    std::fs::create_dir_all(parent)?;
    let temporary = path.with_extension("tmp");
    std::fs::write(&temporary, unit)?;
    std::fs::rename(&temporary, &path)?;
    systemctl(&["daemon-reload"])?;
    if no_start {
        systemctl(&["enable", SERVICE_NAME])?;
    } else {
        systemctl(&["enable", SERVICE_NAME])?;
        systemctl(&["restart", SERVICE_NAME])?;
    }
    println!("Installed {}", path.display());
    Ok(())
}

fn uninstall(apply: bool) -> Result<()> {
    let path = unit_path();
    if !apply {
        println!("Would stop, disable, and remove {}", path.display());
        return Ok(());
    }
    if path.exists() {
        let content = std::fs::read_to_string(&path)?;
        validate_owned_unit(&content)?;
    }
    let _ = std::process::Command::new("systemctl")
        .args(["--user", "disable", "--now", SERVICE_NAME])
        .status();
    if path.exists() {
        std::fs::remove_file(&path)?;
    }
    systemctl(&["daemon-reload"])?;
    println!("Removed {}", path.display());
    Ok(())
}

fn validate_owned_unit(content: &str) -> Result<()> {
    if !content.starts_with(SERVICE_MARKER) {
        anyhow::bail!("refusing to stop or remove a unit not generated by rc003-omarchy");
    }
    Ok(())
}

fn systemctl(arguments: &[&str]) -> Result<()> {
    let status = std::process::Command::new("systemctl")
        .arg("--user")
        .args(arguments)
        .status()
        .with_context(|| format!("systemctl --user {}", arguments.join(" ")))?;
    if !status.success() {
        anyhow::bail!("systemctl --user {} failed", arguments.join(" "));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_contains_user_session_and_explicit_config() {
        let unit = unit_text(
            Path::new("/opt/rc003-omarchy"),
            Path::new("/home/test/config.toml"),
        )
        .unwrap();
        assert!(unit.contains("PartOf=graphical-session.target"));
        assert!(unit.contains("/usr/bin/newgrp input -c"));
        assert!(unit.starts_with(SERVICE_MARKER));
    }

    #[test]
    fn unsafe_paths_are_rejected() {
        for path in ["/tmp/a$b", "/tmp/a`b", "/tmp/a%b", "/tmp/a'b", "/tmp/a b"] {
            assert!(
                validate_safe_path(Path::new(path)).is_err(),
                "accepted {path}"
            );
        }
        assert!(validate_safe_path(Path::new("/opt/rc003-omarchy/config.toml")).is_ok());
    }

    #[test]
    fn service_executable_is_outside_target_directory() {
        assert!(!executable_path().to_string_lossy().contains("target"));
        assert_eq!(
            executable_path().file_name().and_then(|name| name.to_str()),
            Some("rc003-omarchy")
        );
    }

    #[test]
    fn foreign_unit_is_rejected_before_uninstall() {
        assert!(validate_owned_unit(
            "[Unit]
Description=User owned"
        )
        .is_err());
        assert!(validate_owned_unit(
            "# Generated by rc003-omarchy
[Unit]"
        )
        .is_ok());
    }

    #[test]
    fn unit_path_is_in_user_systemd_directory() {
        assert!(unit_path().ends_with("systemd/user/rc003-omarchy.service"));
    }
}
